/**
 * Firebase Security Rules Tests - collections students and tutors must not read
 *
 * Timesheets hold staff files; classes and students hold rosters. The app never
 * reads them from the browser as a student or tutor, so the rules must not allow it.
 *
 * @jest-environment node
 */

const { initializeTestEnvironment } = require('@firebase/rules-unit-testing');
const { seedRuleAccounts } = require('./seedRuleAccounts');

const { assertFails, assertSucceeds } = global;
const fs = require('fs');
const path = require('path');

let testEnv;

beforeAll(async () => {
    testEnv = await initializeTestEnvironment({
        projectId: 'test-project-staff-only',
        firestore: {
            rules: fs.readFileSync(path.join(__dirname, '../../firebase', 'firestore.rules'), 'utf8'),
            host: 'localhost',
            port: Number((process.env.FIRESTORE_EMULATOR_HOST || '127.0.0.1:8080').split(':').at(-1)),
        },
    });
});

afterAll(async () => {
    await testEnv.cleanup();
});

beforeEach(async () => {
    await testEnv.clearFirestore();
    await seedRuleAccounts(testEnv);
    await testEnv.withSecurityRulesDisabled(async (context) => {
        const db = context.firestore();
        await db.collection('timesheets').doc('tutor@kings.edu.au').set({ fileData: 'base64-staff-file' });
        await db.collection('classes').doc('class-1').set({ name: '10 Computing', students: [{ email: 'student@student.kings.edu.au' }] });
        await db.collection('students').doc('student-1').set({ email: 'student@student.kings.edu.au' });
    });
});

const as = (email, defaultRole) => testEnv.authenticatedContext(email, { email, defaultRole, userRoles: [] }).firestore();

describe('Firebase Security Rules - staff-only collections', () => {
    test.each([
        ['student', 'student@student.kings.edu.au'],
        ['tutor', 'tutor@kings.edu.au'],
        ['coach', 'coach@kings.edu.au'],
    ])('a %s CANNOT read timesheets, classes or student records', async (role, email) => {
        const db = as(email, role);

        await assertFails(db.collection('timesheets').get());
        // Not even the tutor's own file: timesheets are generated by the server.
        await assertFails(db.collection('timesheets').doc('tutor@kings.edu.au').get());
        await assertFails(db.collection('classes').get());
        await assertFails(db.collection('students').get());
    });

    test('a teacher CAN read classes and student records but not timesheets', async () => {
        const db = as('teacher@kings.edu.au', 'teacher');

        await assertSucceeds(db.collection('classes').get());
        await assertSucceeds(db.collection('students').get());
        await assertFails(db.collection('timesheets').get());
    });

    test('an admin CAN read and replace timesheets', async () => {
        const db = as('admin@kings.edu.au', 'admin');

        await assertSucceeds(db.collection('timesheets').get());
        await assertSucceeds(db.collection('timesheets').doc('tutor@kings.edu.au').set({ fileData: 'replacement' }));
    });
});
